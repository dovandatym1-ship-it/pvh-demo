-- Database behavior verification, not browser E2E. All fixtures are rolled back.
begin;
create temporary table pvh_checks(name text primary key,passed boolean not null);
grant select,insert on pvh_checks to authenticated,anon;
create temporary table pvh_fixture(key text primary key,value text);
grant select,insert,update on pvh_fixture to authenticated,anon;
create function pg_temp.check_true(p_name text,p_value boolean) returns void language plpgsql as $$
begin if p_value is distinct from true then raise exception 'CHECK_FAILED: %',p_name; end if; insert into pvh_checks values(p_name,true); end; $$;
create function pg_temp.expect_error(p_name text,p_query text,p_pattern text) returns void language plpgsql as $$
begin
 begin execute p_query;
 exception when others then perform pg_temp.check_true(p_name,sqlerrm like p_pattern); return;
 end;
 raise exception 'EXPECTED_ERROR_NOT_RAISED: %',p_name;
end; $$;
insert into pvh_fixture select 'tenant',id::text from public.tenants;
insert into pvh_fixture values('officer',gen_random_uuid()::text),('viewer',gen_random_uuid()::text),('outsider',gen_random_uuid()::text),('admin',gen_random_uuid()::text);
insert into auth.users(id,email) select value::uuid,'pvh-test-'||key||'@example.invalid' from pvh_fixture where key in('officer','viewer','outsider','admin');
insert into public.profiles(id,tenant_id,full_name) select f.value::uuid,t.id,'Test '||f.key from pvh_fixture f cross join public.tenants t where f.key in('officer','viewer','admin');
insert into public.memberships(tenant_id,user_id) select t.id,f.value::uuid from public.tenants t cross join pvh_fixture f where f.key in('officer','viewer','admin');
insert into public.membership_roles(membership_id,role_code)
select m.id,case f.key when 'officer' then 'WORK_OFFICER' when 'viewer' then 'WORK_VIEWER' else 'SYSTEM_ADMIN' end
from public.memberships m join pvh_fixture f on f.value=m.user_id::text where f.key in('officer','viewer','admin');
select pg_temp.check_true('one_commune',count(*)=1) from public.tenants;
select pg_temp.expect_error('second_commune_rejected',$q$insert into public.tenants(code,name) values('TN-DEMO-B','Not permitted')$q$,'%unique constraint%');
select pg_temp.check_true('all_tables_force_rls',bool_and(c.relrowsecurity and c.relforcerowsecurity)) from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind='r';
select pg_temp.check_true('evidence_private',not public) from storage.buckets where id='evidence';
set local role anon;
select pg_temp.expect_error('anonymous_table_denied','select * from public.work_items','%permission denied%');
select pg_temp.expect_error('anonymous_rpc_denied',$q$select app.create_work_item('anon','Anonymous')$q$,'%permission denied%');
reset role;
select set_config('request.jwt.claims',json_build_object('sub',(select value from pvh_fixture where key='viewer'),'role','authenticated','user_metadata',json_build_object('role','SYSTEM_ADMIN'))::text,true);
set local role authenticated;
select pg_temp.check_true('viewer_read_grant',app.has_permission((select value::uuid from pvh_fixture where key='tenant'),'m01:work:read'));
select pg_temp.check_true('viewer_no_create',not app.has_permission((select value::uuid from pvh_fixture where key='tenant'),'m01:work:create'));
select pg_temp.expect_error('viewer_rpc_write_denied',$q$select app.create_work_item('reader','No write')$q$,'%FORBIDDEN%');
select pg_temp.expect_error('client_cannot_elevate_roles',$q$update public.memberships set permissions=array['all']$q$,'%permission denied%');
select pg_temp.expect_error('client_cannot_forge_audit',$q$insert into public.audit_log(tenant_id,actor_id,action,entity_type,entity_id) values(gen_random_uuid(),auth.uid(),'FAKE','work','x')$q$,'%permission denied%');
select pg_temp.check_true('only_own_membership_visible',count(*)=1) from public.memberships;
reset role;
select set_config('request.jwt.claims',json_build_object('sub',(select value from pvh_fixture where key='admin'),'role','authenticated')::text,true);
set local role authenticated;
select pg_temp.check_true('admin_no_implicit_business_read',not app.has_permission((select value::uuid from pvh_fixture where key='tenant'),'m01:work:read'));
select pg_temp.expect_error('admin_no_implicit_business_write',$q$select app.create_work_item('admin','No implicit rights')$q$,'%FORBIDDEN%');
reset role;
select set_config('request.jwt.claims',json_build_object('sub',(select value from pvh_fixture where key='officer'),'role','authenticated')::text,true);
set local role authenticated;
select pg_temp.expect_error('client_direct_insert_denied',$q$insert into public.work_items(title) values('bypass')$q$,'%permission denied%');
select pg_temp.expect_error('spoof_commune_denied',$q$select app.create_work_item('spoof','Spoof',p_tenant_id=>gen_random_uuid())$q$,'%FORBIDDEN%');
select pg_temp.expect_error('empty_title_rejected',$q$select app.create_work_item('empty','  ')$q$,'%VALIDATION_ERROR%');
select pg_temp.expect_error('empty_idempotency_rejected',$q$select app.create_work_item('','Valid')$q$,'%VALIDATION_ERROR%');
select pg_temp.expect_error('foreign_assignment_denied',$q$select app.create_work_item('assign','Bad assignment',p_assigned_to=>gen_random_uuid())$q$,'%FORBIDDEN_ASSIGN%');
insert into pvh_fixture select 'work',app.create_work_item('first','Test work')->>'id';
select pg_temp.check_true('create_and_read_back',count(*)=1) from public.work_items;
select pg_temp.check_true('idempotency_same_result',(app.create_work_item('first','Test work')->>'id')=(select value from pvh_fixture where key='work'));
select pg_temp.check_true('idempotency_marked_cached',(app.create_work_item('first','Test work')->>'cached')::boolean);
select pg_temp.expect_error('idempotency_changed_payload_denied',$q$select app.create_work_item('first','Changed payload')$q$,'%IDEMPOTENCY_CONFLICT%');
select pg_temp.check_true('officer_no_audit_read',count(*)=0) from public.audit_log;
insert into pvh_fixture select 'evidence',app.register_evidence((select value::uuid from pvh_fixture where key='work'),'test.pdf')->>'object_path';
select pg_temp.check_true('own_evidence_read_allowed',pvh_private.can_access_evidence((select value from pvh_fixture where key='evidence'),'read'));
select pg_temp.check_true('unknown_evidence_denied',not pvh_private.can_access_evidence('../other/test.pdf','read'));
reset role;
select pg_temp.check_true('one_create_one_event',count(*)=1) from public.work_item_events where work_item_id=(select value::uuid from pvh_fixture where key='work');
select pg_temp.check_true('one_create_one_audit',count(*)=1) from public.audit_log where action='CREATE_WORK_ITEM' and entity_id=(select value from pvh_fixture where key='work');
select pg_temp.check_true('audit_actor_from_account',bool_and(actor_id=(select value::uuid from pvh_fixture where key='officer'))) from public.audit_log;
select pg_temp.expect_error('audit_update_immutable',$q$update public.audit_log set action='FAKE'$q$,'%APPEND_ONLY%');
select pg_temp.expect_error('audit_delete_immutable',$q$delete from public.audit_log$q$,'%APPEND_ONLY%');
select set_config('request.jwt.claims',json_build_object('sub',(select value from pvh_fixture where key='outsider'),'role','authenticated')::text,true);
set local role authenticated;
select pg_temp.check_true('outsider_no_rows',count(*)=0) from public.work_items;
select pg_temp.check_true('outsider_no_membership',count(*)=0) from public.memberships;
select pg_temp.check_true('outsider_no_evidence',not pvh_private.can_access_evidence((select value from pvh_fixture where key='evidence'),'read'));
select pg_temp.expect_error('outsider_rpc_denied',$q$select app.create_work_item('outsider','Denied')$q$,'%FORBIDDEN%');
reset role;
update public.memberships set valid_from=now()-interval '2 days',valid_to=now()-interval '1 day' where user_id=(select value::uuid from pvh_fixture where key='officer');
select set_config('request.jwt.claims',json_build_object('sub',(select value from pvh_fixture where key='officer'),'role','authenticated')::text,true);
set local role authenticated;
select pg_temp.check_true('expired_no_read',count(*)=0) from public.work_items;
select pg_temp.expect_error('expired_same_jwt_no_write',$q$select app.create_work_item('expired','Denied')$q$,'%FORBIDDEN%');
reset role;
update public.memberships set valid_to=null where user_id=(select value::uuid from pvh_fixture where key='officer');
update public.module_entitlements set enabled=false where module_key='m01';
set local role authenticated;
select pg_temp.expect_error('disabled_module_denied',$q$select app.create_work_item('disabled','Denied')$q$,'%FORBIDDEN%');
reset role;
update public.module_entitlements set enabled=true where module_key='m01';
delete from public.role_permissions where role_code='WORK_OFFICER' and permission_code='m01:work:create';
set local role authenticated;
select pg_temp.check_true('role_change_same_jwt_effective',not app.has_permission((select value::uuid from pvh_fixture where key='tenant'),'m01:work:create'));
select pg_temp.check_true('role_projection_refreshed',not('m01:work:create'=any(permissions))) from public.memberships where user_id=auth.uid();
reset role;

-- Scope and account-context checks after the context migration.
select pg_temp.check_true('context_bound_to_account',(app.get_account_context()->>'userId')=(select value from pvh_fixture where key='officer'));
select pg_temp.check_true('context_single_commune',(app.get_account_context()->>'singleCommune')::boolean);
insert into public.role_permissions values('WORK_OFFICER','m01:work:create');
insert into public.org_units(tenant_id,code,name,kind) select id,'TEST-A','Test hamlet A','HAMLET' from public.tenants;
insert into public.org_units(tenant_id,code,name,kind) select id,'TEST-B','Test hamlet B','HAMLET' from public.tenants;
insert into pvh_fixture select 'unit_a',id::text from public.org_units where code='TEST-A';
insert into pvh_fixture select 'unit_b',id::text from public.org_units where code='TEST-B';
update public.memberships set scopes=jsonb_build_object('org_unit_ids',jsonb_build_array((select value from pvh_fixture where key='unit_a'))) where user_id=(select value::uuid from pvh_fixture where key='officer');
set local role authenticated;
select pg_temp.expect_error('outside_assignment_scope_denied',$q$select app.create_work_item('wrong-scope','Denied',p_hamlet_id=>(select value::uuid from pvh_fixture where key='unit_b'))$q$,'%FORBIDDEN_SCOPE%');
select pg_temp.check_true('record_outside_scope_hidden',count(*)=0) from public.work_items;
select pg_temp.check_true('same_scope_create_allowed',(app.create_work_item('right-scope','Allowed',p_hamlet_id=>(select value::uuid from pvh_fixture where key='unit_a'))->>'id') is not null);
reset role;
update public.memberships set is_active=false where user_id=(select value::uuid from pvh_fixture where key='officer');
set local role authenticated;
select pg_temp.expect_error('revoked_context_denied','select app.get_account_context()','%FORBIDDEN%');
reset role;

select jsonb_build_object('passed',count(*),'failed',count(*) filter(where not passed),'checks',jsonb_agg(name order by name)) as verification from pvh_checks;
rollback;
